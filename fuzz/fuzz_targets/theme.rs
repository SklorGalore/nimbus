//! Fuzz the theme parser: `Theme::parse` on arbitrary text, over either
//! built-in theme, must never panic, and every colour it hands the
//! renderer must be a real one (channels between 0 and 1), for every
//! capture of every grammar.
//!
//! As in the `config` target, the app's own `theme.rs` is compiled in
//! unchanged with `#[path]`. It needs `config.rs` too (for the config
//! folder) and two types from the render and syntax crates, which this
//! crate depends on behind the `app-theme` feature. Run it with
//! `cargo fuzz run theme --features app-theme`.

#![no_main]

use libfuzzer_sys::fuzz_target;

#[allow(dead_code, reason = "the app's module, of which this uses a part")]
#[path = "../../crates/app/src/config.rs"]
mod config;

#[allow(dead_code, reason = "the app's module, of which this uses a part")]
#[path = "../../crates/app/src/theme.rs"]
mod theme;

use theme::{Color, Look, Theme};

fuzz_target!(|data: &[u8]| {
    let Some((&which, rest)) = data.split_first() else {
        return;
    };
    let base_name = if which % 2 == 0 { "dark" } else { "light" };
    let Some(base) = Theme::built_in(base_name) else {
        panic!("built-in theme {base_name} missing");
    };
    let text = String::from_utf8_lossy(rest);
    let (mut theme, _warnings) = Theme::parse("fuzz", &text, &base);
    assert_eq!(theme.base, base.base, "parse keeps the base theme's name");
    for c in ui_colors(&theme) {
        check_color(c);
    }
    theme.resolve_tables();
    for table in 0..nimbus_syntax::registry::TABLES {
        let Some(names) = nimbus_syntax::registry::capture_table(table) else {
            continue;
        };
        for (i, name) in names.iter().enumerate() {
            let index = u32::try_from(i).unwrap_or(u32::MAX);
            let look = theme.look(table, index);
            assert_eq!(look, theme.named(name), "table {table} capture {name}");
            if let Some(Look { color: Some(c), .. }) = look {
                check_color(c);
            }
        }
    }
});

/// A few interface colours (the struct's fields are generated by a macro
/// whose name list is test-only, so these are spelled out).
fn ui_colors(theme: &Theme) -> [Color; 4] {
    [
        theme.ui.background,
        theme.ui.text,
        theme.ui.cursor,
        theme.ui.selection,
    ]
}

fn check_color(c: Color) {
    assert!(
        c.iter().all(|v| (0.0..=1.0).contains(v)),
        "colour out of range: {c:?}"
    );
}
